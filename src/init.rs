//! `init`: prepares a vault, empty or not. Existing notes are never moved or
//! changed; their original state is committed before anything else happens.

use std::fs;
use std::path::Path;

use anyhow::{bail, Context, Result};

use crate::git::{commit_staged, git, git_ok};
use crate::vault::{canonical, Vault};

pub const RULES_FILE: &str = "WIKI.md";
pub const INDEX_FILE: &str = "WIKI-INDEX.md";
const INDEX_MARKER: &str = "<!-- generated by wiki-llm-mcp: do not edit -->";
const GITIGNORE_ENTRIES: [&str; 4] = [
    ".obsidian/workspace*.json",
    ".obsidian/cache",
    ".trash/",
    ".DS_Store",
];
const DEFAULT_RULES: &str = include_str!("default_wiki_rules.md");

#[derive(Debug, PartialEq)]
pub struct InitReport {
    pub pages_indexed: usize,
    pub snapshot_committed: bool,
    pub git_initialized: bool,
}

fn ensure_gitignore(root: &Path) -> Result<()> {
    let path = root.join(".gitignore");
    let mut content = fs::read_to_string(&path).unwrap_or_default();
    let missing: Vec<&str> = GITIGNORE_ENTRIES
        .iter()
        .copied()
        .filter(|entry| !content.lines().any(|line| line.trim() == *entry))
        .collect();
    if missing.is_empty() {
        return Ok(());
    }
    if !content.is_empty() && !content.ends_with('\n') {
        content.push('\n');
    }
    content.push_str(&missing.join("\n"));
    content.push('\n');
    fs::write(&path, content).context("could not write .gitignore")
}

fn page_title(vault: &Vault, page: &str) -> String {
    vault
        .read_page(page)
        .ok()
        .and_then(|content| {
            content
                .lines()
                .find_map(|l| l.strip_prefix("# ").map(|t| t.trim().to_string()))
        })
        .filter(|title| !title.is_empty())
        .unwrap_or_else(|| {
            let stem = page.rsplit('/').next().unwrap_or(page);
            stem.strip_suffix(".md").unwrap_or(stem).to_string()
        })
}

/// Catalog of every page. Generated, so that no writer has to edit a shared file.
pub fn render_index(vault: &Vault) -> (String, usize) {
    let pages: Vec<String> = vault
        .all_pages()
        .into_iter()
        .filter(|p| p != INDEX_FILE && p != RULES_FILE)
        .collect();
    let mut out = format!("{INDEX_MARKER}\n# Wiki index\n\n");
    for page in &pages {
        let target = page.strip_suffix(".md").unwrap_or(page);
        // `|` and `]` would break the wikilink syntax.
        let title = page_title(vault, page).replace(['|', ']'], " ");
        out.push_str(&format!("- [[{target}|{title}]]\n"));
    }
    (out, pages.len())
}

/// Rewrites the catalog if this tool owns it; a foreign file is left alone.
/// Returns whether the file was (re)written.
pub fn refresh_index(vault: &Vault) -> Result<bool> {
    let path = vault.root().join(INDEX_FILE);
    let owned = fs::read_to_string(&path).is_ok_and(|c| c.starts_with(INDEX_MARKER));
    if owned {
        fs::write(&path, render_index(vault).0).context("could not write the index")?;
    }
    Ok(owned)
}

fn create_kept_dir(root: &Path, name: &str) -> Result<()> {
    let dir = root.join(name);
    fs::create_dir_all(&dir).with_context(|| format!("could not create {name}/"))?;
    if fs::read_dir(&dir)?.next().is_none() {
        fs::write(dir.join(".gitkeep"), "")?;
    }
    Ok(())
}

/// Whether `init` already ran on this folder.
pub fn is_initialized(path: &Path) -> bool {
    path.join(".git").exists() && path.join(INDEX_FILE).exists()
}

pub fn init(path: &Path) -> Result<InitReport> {
    fs::create_dir_all(path).with_context(|| format!("could not create {}", path.display()))?;
    let root = canonical(path)?;

    // Everything that can refuse comes first, so a refusal leaves the vault untouched.
    // A folder picked by mistake would have all of its files committed.
    let home = std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .and_then(|home| canonical(Path::new(&home)).ok());
    if root.parent().is_none() || home.as_deref() == Some(root.as_path()) {
        bail!(
            "a home folder or a whole disk cannot be a vault: choose the folder that holds \
             the notes"
        );
    }
    let index_path = root.join(INDEX_FILE);
    if index_path.exists() {
        let existing = fs::read_to_string(&index_path).unwrap_or_default();
        if !existing.starts_with(INDEX_MARKER) {
            bail!("{INDEX_FILE} already exists and was not generated by this tool");
        }
    }
    let toplevel = git(&root, &["rev-parse", "--show-toplevel"])?;
    let is_repo = toplevel.status.success();
    if is_repo {
        let top = String::from_utf8_lossy(&toplevel.stdout);
        if canonical(Path::new(top.trim()))? != root {
            bail!("this folder is inside another Git repository: the vault must have its own");
        }
    }

    let had_content = fs::read_dir(&root)?
        .filter_map(|e| e.ok())
        .any(|e| e.file_name() != ".git");
    if !is_repo {
        git_ok(&root, &["init", "-q", "-b", "main"])?;
        // Notes keep the line endings they were written with, on every device:
        // a page must not change because Git checked it out again.
        git_ok(&root, &["config", "core.autocrlf", "false"])?;
    }

    // The ignore rules go first, so Obsidian's state stays out of the snapshot.
    ensure_gitignore(&root)?;
    let mut snapshot_committed = false;
    if had_content {
        git_ok(&root, &["add", "-A"])?;
        snapshot_committed = commit_staged(&root, "wiki-llm-mcp: original state of the vault")?;
    }

    create_kept_dir(&root, "raw")?;
    create_kept_dir(&root, "wiki")?;
    let rules_path = root.join(RULES_FILE);
    if !rules_path.exists() {
        fs::write(&rules_path, DEFAULT_RULES)?;
    }
    let vault = Vault::open(&root)?;
    let (index, pages_indexed) = render_index(&vault);
    fs::write(&index_path, index)?;

    git_ok(
        &root,
        &[
            "add",
            "--",
            ".gitignore",
            RULES_FILE,
            INDEX_FILE,
            "raw",
            "wiki",
        ],
    )?;
    commit_staged(&root, "wiki-llm-mcp: set up the vault")?;

    Ok(InitReport {
        pages_indexed,
        snapshot_committed,
        git_initialized: !is_repo,
    })
}
